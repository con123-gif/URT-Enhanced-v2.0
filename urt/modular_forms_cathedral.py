# ── Perfect numbers ────────────────────────────────────────────────────────────
# Even perfect numbers: 2^(p-1)·(2^p-1) with 2^p-1 Mersenne prime.
PERFECT_1 =    6   # p=2: 2^1 × 3   = D! = 6
PERFECT_2 =   28   # p=3=D: 2^2 × 7 = (D+1)×(D!+1) = 4×7
PERFECT_3 =  496   # p=5=q: 2^4 × 31 = 2^(D+1)×(2^q-1) = 16×31
