TAU_AT_2 = TAU_RAMANUJAN[2]   # = -24
TAU_AT_N = TAU_RAMANUJAN[N]   # τ(13)

# ── Leech lattice ──────────────────────────────────────────────────────────────
LEECH_DIM = 2 * V             # = 24  (dimension of the Leech lattice)
# Kissing number of Λ₂₄: 196560 = 2^4 × 3^3 × 5 × 7 × 13
LEECH_KISSING = 2**(D+1) * D**D * q * (factorial(D)+1) * N   # = 196560
LEECH_KISSING_EXACT = 196560

# The E₈ lattice kissing number is 240 = 4G (already from string_landscape)
E8_KISSING = 4 * G            # = 240

# ── Niemeier lattices ──────────────────────────────────────────────────────────
# There are exactly 24 = 2V positive-definite even unimodular lattices in R^24
