# ── Audit / CI gate ──────────────────────────────────────────────────────

def template_coverage_summary() -> Dict[str, int]:
    """Count observables per family."""
    cls = canonical_classification()
    out = {}
    for c in cls:
        out[c.family] = out.get(c.family, 0) + 1
    return out


def template_fit_quality() -> List[Tuple[str, str, Optional[float]]]:
    """Return (name, family, rel_err) for each row."""
    out = []
    for c in canonical_classification():
        if c.observed is None or c.observed == 0:
            out.append((c.name, c.family, None))
        else:
            re = (c.predicted - c.observed) / c.observed
            out.append((c.name, c.family, re))
    return out


def unified_recipe_audit_passes(tol: float = 0.05) -> bool:
    """
    CI gate: every classified observable that has an observation
    matches its template prediction to within `tol` rel-err.

    Default tol=5%; the v9 ledger nearly all sits within 1% but we
    use 5% here to give the audit some margin against future
    refinements (the audit is structural, not numerical).
    """
    for name, fam, re in template_fit_quality():
        if re is None:
            continue
        if abs(re) > tol:
            return False
    return True


def information_delivered_bits() -> float:
    """Sum of log2(1/|rel_err|) across measured observables."""
    total = 0.0
    for name, fam, re in template_fit_quality():
        if re is None or re == 0:
            continue
        total += math.log2(1.0 / abs(re))
    return total


def template_DOF_per_observable() -> Dict[str, float]:
    """Effective per-observable DOF for each template.

    These are honest estimates from the slot cardinalities used in the
    classification:
        INT:            ~50 atomic Cathedral integers, 2-3 ops →   ~9 bits
        GAMMA_LADDER:   coeff (≈50) × {8 γ exponents}            ≈ 12 bits
        DELTA_STAR_LIN: coeff (≈50) × {power ∈ {1,2}}            ≈ 10 bits
        TRIG_WRAPPER:   coeff × {4 trig} × {7 arg shapes}        ≈ 12 bits

    Each template family DOF is a "per-observable freedom budget":
    log2(# distinct expressions a row of that family could take).
    """
    return {
        "INT":            8.6,
        "GAMMA_LADDER":  12.0,
        "DELTA_STAR_LIN": 9.6,
        "TRIG_WRAPPER":  11.5,
    }


def total_template_budget_bits() -> float:
    dof = template_DOF_per_observable()
    cls = canonical_classification()
    total = 0.0
    for c in cls:
        if c.observed is None: continue
        total += dof.get(c.family, 12.0)
    return total


def net_information_bits() -> float:
    return information_delivered_bits() - total_template_budget_bits()


def print_unified_recipe_report() -> None:
    print("=" * 78)
    print("Unified Recipe Audit — 4-template scheme")
    print("=" * 78)
    print("Templates:")
    print("  INT             : pure Cathedral-integer expression P(D,q,V,N,E,F,G)")
    print("  GAMMA_LADDER    : C · γ^k,   k ∈ {-7, 1, 2, 3, 5, 9, 64}")
    print("  DELTA_STAR_LIN  : C · δ★^p, p ∈ {1, 2}")
    print("  TRIG_WRAPPER    : T(arg)·scale, T ∈ {sin, cos, atan, asin}")
    print("-" * 78)

    cov = template_coverage_summary()
    for fam in ("INT", "GAMMA_LADDER", "DELTA_STAR_LIN", "TRIG_WRAPPER"):
        print(f"  {fam:<18} {cov.get(fam, 0)} observables")

    print()
    print(f"{'observable':<28} {'family':<18} {'rel_err':>10}  detail")
    print("-" * 78)
    for c in canonical_classification():
        if c.observed is None or c.observed == 0:
            rs = "—"
        else:
            re = (c.predicted - c.observed)/c.observed
            rs = f"{re*100:+.3f}%"
        print(f"  {c.name:<28} {c.family:<18} {rs:>10}  {c.detail}")
    print("-" * 78)
    info  = information_delivered_bits()
    budget = total_template_budget_bits()
    print(f"Information delivered:         {info:.1f} bits")
    print(f"Template budget (sum DOFs):    {budget:.1f} bits")
    print(f"Net information:               {info - budget:+.1f} bits")
    print(f"Verdict: {'TIGHT' if (info - budget) > 0 else 'LOOSE (curve-fitting)'}")
    print("=" * 78)


