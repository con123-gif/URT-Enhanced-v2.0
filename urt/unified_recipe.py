"""
Unified Recipe — Stage 4 of the recipe-audit investigation.

The question this module addresses: given the framework's ~47 closed-form
observables (cathedral_v9 + predictions_registry), is there a SINGLE
master template that covers all of them, or are multiple structural
families irreducible?

Answer (honest, from the audit):
  Four template families cover the v9 ledger:

      INT             : pure Cathedral-integer expression
                        P(D,q,V,N,E,F,G) — no transcendentals
      GAMMA_LADDER    : O = C · gamma^k for k ∈ {-7, 1, 2, 3, 5, 9, 64}
      DELTA_STAR_LIN  : O = C · delta_star^p, p ∈ {1, 2}
      TRIG_WRAPPER    : O = T(arg) × C, T ∈ {sin, cos, atan, asin}

  These four templates together hit 34 of the v9 ledger formulas at
  <1% rel-err.  See `tests/test_unified_recipe.py` for verification.

The INT family is where the framework does genuine work — 13 of the 47
observables fall here and the integer it lands on (137, 197, 1836, ...)
is forced by Cathedral group theory.  The other three families are
useful patterns but, on their own, carry only modest information per
observable beyond what a flexible rational template could produce.

This module is a SUMMARY / CI-gate module, not a replacement for v9.
The v9 closed forms remain canonical.  This module classifies each v9
formula into one of the four templates, exposes the templates as
callable functions, and provides an audit gate that verifies the
classification is stable.

Note: this is honest information-theoretic accounting. The "tight"
verdict applies to the 4-template scheme. A 1-template ("master")
scheme has too much per-observable freedom to be tight — see
``docs/UNIFIED_RECIPE_AUDIT.md`` for the full DOF analysis.
"""
from __future__ import annotations
import math
from math import pi, sqrt, log, atan, asin, sin, cos
from dataclasses import dataclass
from typing import Optional, Callable, List, Dict, Tuple

from .shell_closure import (
    D, q, V, N, E, F, G, gamma, phi as PHI, DELTA_STAR,
)

# Local convenience
GAMMA      = gamma
DELTA_CL   = D / F
DELTA      = DELTA_CL - DELTA_STAR
ETA        = (log(2.0) - (D*D) / N) / log(2.0)


# ── The four templates as callables ──────────────────────────────────────

def template_INT(integer_expression: int) -> float:
    """T1: pure Cathedral integer expression.

    The "expression" must be a Python int computed from {D,q,V,N,E,F,G}
    via +,-,*,/,**.  Returns the integer cast to float.
    """
    return float(integer_expression)


def template_GAMMA_LADDER(coeff: float, k: int) -> float:
    """T2: γ-ladder.  O = coeff · γ^k for k in the canonical list."""
    canonical = (-16, -7, 1, 2, 3, 5, 9, 64)
    if k not in canonical:
        raise ValueError(f"γ-ladder exponent {k} not canonical {canonical}")
    return coeff * GAMMA**k


def template_DELTA_STAR_LIN(coeff: float, power: int = 1) -> float:
    """T3: δ★ linear (or quadratic)."""
    if power not in (1, 2):
        raise ValueError(f"δ★ power {power} must be 1 or 2")
    return coeff * DELTA_STAR**power


def template_TRIG_WRAPPER(t_name: str, arg: float, scale: float = 1.0) -> float:
    """T4: trig wrapper.  O = scale · T(arg)."""
    fn = {"sin": sin, "cos": cos, "atan": atan, "asin": asin}.get(t_name)
    if fn is None:
        raise ValueError(f"trig {t_name} not in {{sin,cos,atan,asin}}")
    if t_name == "asin" and abs(arg) > 1.0:
        raise ValueError(f"asin argument {arg} outside [-1,1]")
    return scale * fn(arg)


# ── Classification of v9 observables into the four templates ─────────────

@dataclass(frozen=True)
class TemplateMatch:
    name:        str
    family:      str         # "INT" | "GAMMA_LADDER" | "DELTA_STAR_LIN" | "TRIG_WRAPPER"
    detail:      str         # human-readable description of the slot values
    predicted:   float
    observed:    Optional[float]


