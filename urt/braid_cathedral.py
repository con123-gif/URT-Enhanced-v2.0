def catalan(n: int) -> int:
    """nth Catalan number C_n = C(2n,n)/(n+1)."""
    return comb(2 * n, n) // (n + 1)


# C_D = C_3 = 5 = q ← Cathedral!
C_D_CATALAN = catalan(D)                    # = 5 = q
IDENTITY_C_D_IS_q: bool = (C_D_CATALAN == q)

