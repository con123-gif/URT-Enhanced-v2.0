# ── Helper functions ──────────────────────────────────────────────────────────

def _catalan(n: int) -> int:
    """Return the n-th Catalan number C(2n,n)/(n+1)."""
    return comb(2 * n, n) // (n + 1)


def _partition_count(n: int) -> int:
    """Return p(n), the number of integer partitions of n."""
    if n < 0:
        return 0
    dp = [0] * (n + 1)
    dp[0] = 1
    for i in range(1, n + 1):
        for j in range(i, n + 1):
            dp[j] += dp[j - i]
    return dp[n]


def rank_K0_Pn(n: int) -> int:
    """Return the rank of K_0(P^n) = n+1 (Beilinson exceptional collection)."""
    return n + 1


