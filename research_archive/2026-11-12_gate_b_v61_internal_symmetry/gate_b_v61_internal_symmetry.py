ok((ns, nd, ns * nd) == (48, 11, 528), "48 sites, 11 directions, 528 links")
half, sixteenth = G(Fr(1, 2)), G(Fr(1, 16))
def fwd(d):
    return ms(ma(gam[d + 1], ms(I4, G(-r))), half) if d < 3 else ms(ma(gam[0], ms(I4, G(-1))), sixteenth)
def bwd(d):
    return ms(ma(ms(gam[d + 1], G(-1)), ms(I4, G(-r))), half) if d < 3 else ms(ma(ms(gam[0], G(-1)), ms(I4, G(-1))), sixteenth)
# terms[(x,y)] = list of (link, conj_flag, 4x4 exact matrix T) with block_xy(h(theta)) = sum e^{+-i theta_link} T
terms = {}
for d, disp in enumerate(DIRS):
    rev = tuple(-v for v in disp)
    for x, site in enumerate(SITES):
        y = IDX[v61.periodic_shift(site, disp)]
        z = IDX[v61.periodic_shift(site, rev)]
        terms.setdefault((x, y), []).append((x * nd + d, 0, mm(g5, ms(fwd(d), G(v61.antiperiodic_sign(site, disp))))))
        terms.setdefault((x, z), []).append((z * nd + d, 1, mm(g5, ms(bwd(d), G(v61.antiperiodic_sign(site, rev))))))
ok(all(x != y for x, y in terms), "no link term is site-diagonal")
def h_model(theta):
    h = np.zeros((4 * ns, 4 * ns), complex)
    onsite = tonp(mm(g5, ms(I4, G(3 * r + 1 - M))))
    for x in range(ns): h[4*x:4*x+4, 4*x:4*x+4] = onsite
    for (x, y), lst in terms.items():
        for l, cj, T in lst:
            ph = np.exp(-1j * theta[l]) if cj else np.exp(1j * theta[l])
            h[4*x:4*x+4, 4*y:4*y+4] += ph * tonp(T)
    return h
G5 = np.kron(np.eye(ns), g5_np)
def h_v61(theta):
    return G5 @ (v61.wilson_operator_from_links(np.exp(1j * theta.reshape(ns, nd))) - float(M) * np.eye(4 * ns))
theta_flat = np.zeros(ns * nd)
theta_det = np.array([((l + 1) * 3) % 17 / 7.0 for l in range(ns * nd)])   # deterministic, non-flat
for name, th in (("flat", theta_flat), ("deterministic non-flat", theta_det)):
    err = np.abs(h_model(th) - h_v61(th)).max()
    herm = np.abs(h_v61(th) - h_v61(th).conj().T).max()
    ok(err < 1e-13 and herm < 1e-13, f"exact term model == archived v61 Hermitian kernel at {name} links (max diff {err:.1e})")

# A1: site graph and its automorphism order bound (independent re-check of Q4)
adj = np.zeros((ns, ns), int)
for (x, y) in terms: adj[x, y] = adj[y, x] = 1
ok(adj.sum() // 2 == 456, "site graph has 456 simple edges")
common = adj @ adj
slices = [frozenset(np.nonzero((common[x] >= 16) | (np.arange(ns) == x))[0]) for x in range(ns)]
blocks = sorted(set(slices), key=lambda s: min(s))
ok(len(blocks) == 6 and all(len(b) == 8 for b in blocks) and all(sum(x in b for b in blocks) == 1 for x in range(ns)),
   "'>=16 common neighbours' partitions the sites into 6 blocks of 8 (automorphism-invariant blocks)")
for b in blocks:
    sub = nx.from_numpy_array(adj[np.ix_(sorted(b), sorted(b))])
    ok(nx.is_isomorphic(sub, nx.hypercube_graph(3)), "block induces the cube graph Q3 (|Aut| = 48)")
q = np.zeros((6, 6), int)
for i, a in enumerate(blocks):
    for j, b in enumerate(blocks):
        if i != j:
            cnt = adj[np.ix_(sorted(a), sorted(b))].sum(); assert cnt in (0, 64); q[i, j] = cnt // 64
ok(nx.is_isomorphic(nx.from_numpy_array(q), nx.cycle_graph(6)), "block quotient is the 6-cycle, joins complete (|Aut| = 12)")
bound = 12 * 48 ** 6
ok(bound % 5 != 0 and bound % 3 == 0, f"|Aut(site graph)| divides 12*48^6 = {bound}: no element of order 5")
OUT["site_aut_order_divides"] = bound

# A2: per ordered neighbour pair, the link terms are linearly independent and at most two
sizes = {}
for (x, y), lst in terms.items():
    sizes[len(lst)] = sizes.get(len(lst), 0) + 1
    ok_indep = rank_gq([list(key(T)) for _, _, T in lst]) == len(lst)
    if not ok_indep or len(lst) > 2 or len({l for l, _, _ in lst}) != len(lst):
        ok(False, f"pair {(x, y)}: terms not independent / more than two / repeated link")
ok(sizes == {1: 768, 2: 144}, f"ordered pairs by number of independent link terms: {sizes} (1 = temporal, 2 = doubled spatial)")
OUT["ordered_pairs_by_terms"] = sizes

# A3: return operators T T^dagger at each site generate M_4(C)
site_sets = {}
for (x, y), lst in terms.items():
    for _, _, T in lst:
        site_sets.setdefault(x, set()).add(key(mm(T, dag(T))))
distinct = {frozenset(s) for s in site_sets.values()}
ok(len(site_sets) == 48 and len(distinct) == 1, "the set {T T^dagger} of return operators is the same at all 48 sites")
gens = [[list(k[4*i:4*i+4]) for i in range(4)] for k in next(iter(distinct))]
ok(len(gens) == 8, "8 distinct return operators per site (6 spatial, 2 temporal)")
dim = algebra_dim(gens)
ok(dim == 16, f"they generate an algebra of dimension {dim} = 16 over Q(i): all of M_4(C); commutant = scalars")
# the same from the commutant side: {X : [X, S] = 0 for all S} has dimension 1
rows = []
for S in gens:
    for i in range(4):
        for j in range(4):           # entry (i,j) of S X - X S, linear in the 16 unknowns X[k][l]
            row = [Z] * 16
