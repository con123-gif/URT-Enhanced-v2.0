def fm(n): return [[Fr(0)] * n for _ in range(n)]
def fmul(A, B):
    n = len(A); Bt = list(zip(*B))
    return [[sum(a * b for a, b in zip(row, col) if a and b) for col in Bt] for row in A]
def fadd(A, B, s=1): return [[a + s * b for a, b in zip(ra, rb)] for ra, rb in zip(A, B)]
def fscale(A, s): return [[a * s for a in row] for row in A]
def ftr(A): return sum(A[i][i] for i in range(len(A)))
def fT(A): return [list(c) for c in zip(*A)]
def perm_m(p):
    m = fm(20)
    for i, pi in enumerate(p): m[pi][i] = Fr(1)
    return m
I20 = [[Fr(int(i == j)) for j in range(20)] for i in range(20)]
L = fm(20)
for i, f in enumerate(F):
    for j, g in enumerate(F):
        if i != j and len(set(f) & set(g)) == 2: L[i][j] = Fr(-1)
    L[i][i] = Fr(3)
L2 = fmul(L, L)
quad = fadd(fadd(L2, fscale(L, 6), -1), fscale(I20, 4))           # L^2 - 6L + 4 : kills 3 +- sqrt5
def proj(lam, others):
    P = quad; val = Fr(lam * lam - 6 * lam + 4)
    for o in others:
        P = fmul(P, fadd(L, fscale(I20, o), -1)); val *= (lam - o)
    return fscale(P, 1 / val)
P3, P5 = proj(3, (0, 2, 5)), proj(5, (0, 2, 3))
ok(fmul(P3, P3) == P3 and fmul(P5, P5) == P5 and ftr(P3) == 4 and ftr(P5) == 4 and fmul(L, P3) == fscale(P3, 3)
   and fmul(L, P5) == fscale(P5, 5), "P_3, P_5: exact rational rank-4 spectral projectors of the face Laplacian")
