ok(16 - rank_gq(rows) == 1, "commutant of the return operators in M_4(Q(i)) has dimension exactly 1")
OUT["return_algebra_dim"] = dim

# ------------------------------------------------------------------ Part B: hidden 4_3 + 4_5 on the icosahedron faces
print("== Part B: A5-invariant sources of the hidden 4_3 + 4_5 (exact rationals) ==")
phi = (1 + math.sqrt(5)) / 2
V = []
for s1 in (1, -1):
    for s2 in (1, -1):
        V += [(0, s1, s2 * phi), (s1, s2 * phi, 0), (s2 * phi, 0, s1)]
V = np.array(V, float)
E = [(i, j) for i in range(12) for j in range(i + 1, 12) if abs(np.linalg.norm(V[i] - V[j]) - 2) < 1e-9]
ok(len(E) == 30, "icosahedron: 30 edges")
Es = set(E)
F = [f for f in itertools.combinations(range(12), 3) if all(p in Es for p in itertools.combinations(f, 2))]
ok(len(F) == 20, "icosahedron: 20 faces")
FI = {f: i for i, f in enumerate(F)}
auts = list(nx.algorithms.isomorphism.GraphMatcher(nx.Graph(E), nx.Graph(E)).isomorphisms_iter())
ok(len(auts) == 120, "120 graph automorphisms (I_h)")
def proper(a):
    A = np.array([V[a[i]] for i in range(12)])
    R = np.linalg.lstsq(V, A, rcond=None)[0]
    return np.linalg.det(R) > 0
def face_perm(a): return tuple(FI[tuple(sorted(a[v] for v in f))] for f in F)
rot = sorted({face_perm(a) for a in auts if proper(a)})
allp = {face_perm(a) for a in auts}
ok(len(rot) == 60 and len(allp) == 120, "60 rotations (A5) and 120 elements act faithfully on the 20 faces")
