def frank(rows):
    rows = [list(r) for r in rows]; rk = 0
    for col in range(len(rows[0])):
        piv = next((i for i in range(rk, len(rows)) if rows[i][col] != 0), None)
        if piv is None: continue
        rows[rk], rows[piv] = rows[piv], rows[rk]
        pv = rows[rk][col]; rows[rk] = [x / pv for x in rows[rk]]
        for i in range(len(rows)):
            if i != rk and rows[i][col] != 0:
                f = rows[i][col]; rows[i] = [x - f * y for x, y in zip(rows[i], rows[rk])]
        rk += 1
    return rk
flat = lambda m: [x for row in m for x in row]
hid = [fmul(fmul(Ph, a), Ph) for a in A]
ok(frank([flat(m) for m in hid]) == 4, "B2: End_A5(hidden 8) has dimension exactly 4 (= M_2)")
