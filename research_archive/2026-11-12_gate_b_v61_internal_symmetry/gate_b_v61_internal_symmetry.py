# ------------------------------------------------------------------ Gaussian rationals
class G:
    __slots__ = ("a", "b")
    def __init__(s, a=0, b=0): s.a = Fr(a); s.b = Fr(b)
    def __add__(s, o): return G(s.a + o.a, s.b + o.b)
    def __sub__(s, o): return G(s.a - o.a, s.b - o.b)
    def __neg__(s): return G(-s.a, -s.b)
    def __mul__(s, o): return G(s.a * o.a - s.b * o.b, s.a * o.b + s.b * o.a)
    def conj(s): return G(s.a, -s.b)
    def inv(s):
        n = s.a * s.a + s.b * s.b; return G(s.a / n, -s.b / n)
    def zero(s): return s.a == 0 and s.b == 0
    def __eq__(s, o): return s.a == o.a and s.b == o.b
    def __hash__(s): return hash((s.a, s.b))
    def c(s): return complex(float(s.a), float(s.b))
Z, ONE = G(0), G(1)
def mat(np_m):
    m = [[None] * 4 for _ in range(4)]
    for i in range(4):
        for j in range(4):
            z = complex(np_m[i, j]); a, b = round(z.real), round(z.imag)
            assert abs(z - complex(a, b)) < 1e-15
            m[i][j] = G(a, b)
    return m
def mm(A, B): return [[sum((A[i][k] * B[k][j] for k in range(4)), Z) for j in range(4)] for i in range(4)]
def ma(A, B): return [[A[i][j] + B[i][j] for j in range(4)] for i in range(4)]
def ms(A, s): return [[A[i][j] * s for j in range(4)] for i in range(4)]
def dag(A): return [[A[j][i].conj() for j in range(4)] for i in range(4)]
def key(A): return tuple(A[i][j] for i in range(4) for j in range(4))
def tonp(A): return np.array([[A[i][j].c() for j in range(4)] for i in range(4)])
I4 = [[ONE if i == j else Z for j in range(4)] for i in range(4)]
def rank_gq(rows):
    rows = [list(r) for r in rows]; rk = 0; ncol = len(rows[0]) if rows else 0
    for col in range(ncol):
        piv = next((i for i in range(rk, len(rows)) if not rows[i][col].zero()), None)
        if piv is None: continue
        rows[rk], rows[piv] = rows[piv], rows[rk]
        inv = rows[rk][col].inv(); rows[rk] = [x * inv for x in rows[rk]]
        for i in range(len(rows)):
            if i != rk and not rows[i][col].zero():
                f = rows[i][col]; rows[i] = [x - f * y for x, y in zip(rows[i], rows[rk])]
        rk += 1
    return rk
def algebra_dim(gens):
    """dimension over Q(i) of the unital algebra generated by gens (4x4)."""
    basis = [I4]; vecs = [list(key(I4))]; rk = 1; frontier = [I4]
    while frontier:
        new = []
        for W in frontier:
            for g in gens:
                P = mm(W, g)
                if rank_gq(vecs + [list(key(P))]) > rk:
                    vecs.append(list(key(P))); rk += 1; new.append(P)
        frontier = new
    return rk

# ------------------------------------------------------------------ Part A: v61 hop terms, exactly
print("== Part A: local symmetry group of the gauge-covariant v61 Wilson family ==")
gam_np, g5_np = v61.gamma_matrices()
gam = [mat(g) for g in gam_np]; g5 = mat(g5_np)
r, M = Fr(v61.R_EXACT), Fr(v61.M_EXACT)
ok(r != 0, f"Wilson parameter R_EXACT = {r} is non-zero")
SITES, DIRS, IDX = v61.SITES, v61.DIRECTIONS, v61.SITE_INDEX
