#!/usr/bin/env python3
"""Finite regression for the conductor-of-a-product LCM bound.

This is not a Lean replay.  It exhaustively checks the theorem on the group of
real quadratic Dirichlet characters generated by distinct odd-prime factors.
The conductor is recovered from the factor-through definition (constancy on
unit fibres), rather than assigned to the character under test.
"""

from __future__ import annotations

from itertools import combinations
from math import gcd, lcm, prod
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPORT = HERE / "2026-11-24_conductor_product_lcm_bound.md"
PRIMES = (3, 5, 7, 11)


def check(ok: bool, message: str) -> None:
    if not ok:
        raise AssertionError(message)


def divisors(n: int) -> list[int]:
    return [d for d in range(1, n + 1) if n % d == 0]


def legendre(a: int, p: int) -> int:
    a %= p
    if a == 0:
        return 0
    value = pow(a, (p - 1) // 2, p)
    return -1 if value == p - 1 else value


def value(selected: tuple[int, ...], n: int, a: int) -> int:
    # A MulChar, including its mandated zero on nonunits of the ambient level.
    if gcd(a, n) != 1:
        return 0
    return prod(legendre(a, p) for p in selected)


def factors_through(selected: tuple[int, ...], n: int, d: int) -> bool:
    """Unit values descend along (Z/nZ)^* -> (Z/dZ)^*.

    All n used below are squarefree.  Constancy on the fibres is therefore
    equivalent to existence of the lower-level unit character.
    """
    fibres: dict[int, int] = {}
    for a in range(n):
        if gcd(a, n) != 1:
            continue
        residue = a % d
        v = value(selected, n, a)
        if residue in fibres and fibres[residue] != v:
            return False
        fibres[residue] = v
    return True


def recovered_conductor(selected: tuple[int, ...], n: int) -> int:
    return min(d for d in divisors(n) if factors_through(selected, n, d))


def symmetric_difference(a: tuple[int, ...], b: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(sorted(set(a) ^ set(b)))


def main() -> None:
    report = REPORT.read_text(encoding="utf-8")
    anchors = (
        "40e56bab026552e089d7afcfeff08d2defb9c005",
        "0df444a360eaa60ab8c11dca51a86af692955474",
        "Mathlib/NumberTheory/DirichletCharacter/Basic.lean",
        "Mathlib/NumberTheory/MulChar/Basic.lean",
        "conductor_mul_dvd_lcm_conductor",
        "(chi * psi).conductor | lcm(chi.conductor, psi.conductor)",
        "eq_zero_or_neZero",
        "mem_conductorSet_iff_conductor_dvd",
        "RESUME HERE",
    )
    report_checks = 0
    for anchor in anchors:
        check(anchor in report, f"missing report anchor: {anchor}")
        report_checks += 1

    character_checks = 0
    product_checks = 0
    inverse_checks = 0
    fibre_checks = 0

    for width in range(1, len(PRIMES) + 1):
        ps = PRIMES[:width]
        n = prod(ps)
        chars = [tuple(c) for r in range(width + 1) for c in combinations(ps, r)]
        conductors: dict[tuple[int, ...], int] = {}
        for chi in chars:
            c = recovered_conductor(chi, n)
            expected = prod(chi) if chi else 1
            check(c == expected, f"wrong recovered conductor at n={n}, chi={chi}: {c}")
            conductors[chi] = c
            character_checks += 1
            for d in divisors(n):
                # Factor-through levels are exactly the ambient divisors
                # divisible by the recovered conductor in this family.
                observed = factors_through(chi, n, d)
                check(observed == (d % c == 0), f"factor-through mismatch {n=} {chi=} {d=}")
                fibre_checks += 1

            for a in range(n):
                v = value(chi, n, a)
                inv_v = 0 if v == 0 else v  # all values are 0, +1 or -1
                principal = 1 if gcd(a, n) == 1 else 0
                check(v * inv_v == principal, f"character inverse identity failed {n=} {chi=} {a=}")
                inverse_checks += 1

        for chi in chars:
            for psi in chars:
                product = symmetric_difference(chi, psi)
                c_product = conductors[product]
                bound = lcm(conductors[chi], conductors[psi])
                check(bound % c_product == 0, f"LCM bound failed {n=} {chi=} {psi=}")
                product_checks += 1

    # Strictness and orientation: the nontrivial quadratic character modulo 3
    # squares to the principal character, so 1 | 3 but 3 does not divide 1.
    strict_controls = 0
    n = 3
    chi = (3,)
    c = recovered_conductor(chi, n)
    c_square = recovered_conductor((), n)
    check((c, c_square, lcm(c, c)) == (3, 1, 3), "strict cancellation control")
    strict_controls += 1
    check(lcm(c, c) % c_square == 0 and c_square % lcm(c, c) != 0, "reverse bound control")
    strict_controls += 1
    # At a nonunit the group identity character is zero, not scalar one.
    check(value(chi, n, 0) == 0 and value((), n, 0) == 0, "nonunit identity control")
    strict_controls += 1

    # Arithmetic step used by prim_mul, and its necessary coprimality premise.
    euclid_checks = 0
    for m in range(1, 61):
        for q in range(1, 61):
            for c0 in range(1, 61):
                if gcd(m, q) == 1 and (c0 * q) % m == 0:
                    check(c0 % m == 0, f"Euclid removal failed {m=} {q=} {c0=}")
                    euclid_checks += 1
    check((1 * 3) % 3 == 0 and 1 % 3 != 0 and gcd(3, 3) != 1, "noncoprime control")
    strict_controls += 1

    # Degenerate theorem branch: conductor and level are both zero.
    check(0 % 1 == 0 and lcm(0, 0) == 0, "zero-level arithmetic model")
    strict_controls += 1

    print(
        "conductor product LCM regression: OK; "
        f"report_checks={report_checks}, character_checks={character_checks}, "
        f"fibre_checks={fibre_checks}, product_checks={product_checks}, "
        f"inverse_checks={inverse_checks}, euclid_checks={euclid_checks}, "
        f"negative_controls={strict_controls}"
    )


if __name__ == "__main__":
    main()
