def reduce_word(values, echelon):
    """Exact rational row reduction, retaining original-word coefficients."""
    v = [Fraction(z) for z in values]
    coeff = {}
    for pivot, row, combo in echelon:
        factor = v[pivot]
        if factor:
            for j in range(pivot, len(v)):
                v[j] -= factor * row[j]
            for k, z in combo.items():
                coeff[k] = coeff.get(k, 0) + factor * z
    pivot = next((j for j, z in enumerate(v) if z), None)
    return (pivot, v, coeff)

def algebra_certificate(A, B):
    """Construct an exact trace-preserving unital real *-algebra isomorphism.

    All 2d+1 tested words arise from the d accepted basis words by right
    multiplication by S and S^T.  A dependent word must have EXACTLY the
    same rational relation in the partner, not merely equal traces.
    """
    eye = np.eye(64, dtype=object)
    queue = deque([((), eye, eye)])
    echelon, basis = ([], [])
    checked, max_length = (0, 0)
    while queue:
        word, X, Y = queue.popleft()
        checked += 1
        max_length = max(max_length, len(word))
        pivot, residual, coeff = reduce_word([X[i, j] for i, j in orbital_reps], echelon)
        if pivot is None:
            reconstructed = sum((c * basis[k][2] for k, c in coeff.items()), np.zeros((64, 64), dtype=object))
            assert np.array_equal(Y, reconstructed), ('relation mismatch', word)
            continue
        assert int(np.trace(X)) == int(np.trace(Y)), ('trace mismatch', word)
        k = len(basis)
        scale = residual[pivot]
        row = [z / scale for z in residual]
        combo = {j: -z / scale for j, z in coeff.items()}
        combo[k] = Fraction(1, scale)
        echelon.append((pivot, row, combo))
        echelon.sort(key=lambda x: x[0])
        basis.append((word, X, Y))
        assert len(basis) <= 80
        queue.append((word + (0,), X @ A, Y @ B))
        queue.append((word + (1,), X @ A.T, Y @ B.T))
    assert checked == 1 + 2 * len(basis)
    assert basis[0][0] == () and basis[1][0] == (0,) and (basis[2][0] == (1,))
    return (basis, checked, max_length)

def det_mod(X, prime):
    """Deterministic exact determinant in F_prime; no floating-point rank."""
    M = X.copy() % prime
    n = M.shape[0]
    assert M.shape == (n, n)
    determinant = 1
    for col in range(n):
        nonzero = np.nonzero(M[col:, col])[0]
        if not len(nonzero):
            return 0
        pivot = col + int(nonzero[0])
        if pivot != col:
            M[[col, pivot]] = M[[pivot, col]]
            determinant = -determinant
        value = int(M[col, col])
        determinant = determinant * value % prime
        inv = pow(value, -1, prime)
        M[col] = M[col] * inv % prime
        for row in range(col + 1, n):
            if M[row, col]:
                M[row] = (M[row] - M[row, col] * M[col]) % prime
    return determinant % prime

def witness_probe(kind, prime):
    if kind == 'cubic-diagonal':
        return np.diag(np.arange(1, 65, dtype=np.int64) ** 3 % prime)
    assert kind == 'lcg-seed-6'
    x, vals = (6, [])
    for _ in range(4096):
        x = 1664525 * x + 1013904223 & 4294967295
        vals.append(x % prime)
    return np.array(vals, dtype=np.int64).reshape((64, 64))

def casimir_witness(basis, A, B, prime=1009):
    """X=sum_ij (G^-1)_ij B_i R A_j^T; X A=B X, X A^T=B^T X.

    G_ij=Tr(A_i^T A_j).  Trace-preserving *-isomorphism implies the
    trace-dual Casimir tensor is central, so these identities hold over Q
    for EVERY rational R.  The reduction modulo prime only proves det X!=0.
    """
    n = len(basis)
    As = [np.array(X % prime, dtype=np.int64) for _, X, _ in basis]
    Bs = [np.array(Y % prime, dtype=np.int64) for _, _, Y in basis]
    gram = Matrix(n, n, lambda i, j: int(np.sum(As[i] * As[j]) % prime))
    assert all((int(gram[i, j]) % prime == int(np.sum(Bs[i] * Bs[j]) % prime) for i in range(n) for j in range(n)))
    gram_det = det_mod(np.array(gram, dtype=np.int64), prime)
    assert gram_det != 0, ('bad Gram modulus', prime)
    inverse = np.array(gram.inv_mod(prime), dtype=np.int64)
    duals = []
    for i in range(n):
        dual = np.zeros((64, 64), dtype=np.int64)
        for j in range(n):
            dual = (dual + int(inverse[i, j]) * As[j].T) % prime
        duals.append(dual)
    for name in ('cubic-diagonal', 'lcg-seed-6'):
        R = witness_probe(name, prime)
        X = np.zeros((64, 64), dtype=np.int64)
        for i in range(n):
            X = (X + Bs[i] @ R @ duals[i]) % prime
        assert np.array_equal(X @ (A.astype(np.int64) % prime) % prime, B.astype(np.int64) % prime @ X % prime)
        assert np.array_equal(X @ (A.T.astype(np.int64) % prime) % prime, B.T.astype(np.int64) % prime @ X % prime)
        determinant = det_mod(X, prime)
        if determinant:
            return {'probe': name, 'modulus': prime, 'gram_det_mod': gram_det, 'X_det_mod': determinant}
    raise AssertionError('No invertible witness among the two declared probes')
